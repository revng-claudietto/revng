// ---- Data helpers --------------------------------------------------------

interface StatusStats {
    total: number;
    totalTime: number;
    counts: Record<string, number>;
}

// Per-status counts (plus totals) in a single grouped scan, so callers do not
// need to know the set of statuses ahead of time.
function statusStats(db: Database): StatusStats {
    const rows = db.exec({
        sql: "SELECT status, COUNT(*) AS n, SUM(elapsed_time) AS t FROM main GROUP BY status",
        ...sqlOptions,
    });
    const counts: Record<string, number> = {};
    let total = 0;
    let totalTime = 0;
    for (const r of rows) {
        counts[r.status as string] = r.n as number;
        total += r.n as number;
        totalTime += (r.t as number) || 0;
    }
    return { total, totalTime, counts };
}

function statusCount(s: StatusStats, status: string): number {
    return s.counts[status] ?? 0;
}

function distinctSignatures(db: Database, status: string): number {
    const rows = db.exec({
        sql: "SELECT COUNT(DISTINCT stacktrace_id) AS n FROM main WHERE status = ? AND stacktrace_id != ''",
        bind: [status],
        ...sqlOptions,
    });
    return (rows[0]?.n as number) ?? 0;
}

interface StageEntry {
    name: string;
    count: number;
}

function stageEntries(db: Database, category: string, filter: string): StageEntry[] {
    const rows = db.exec({
        sql: "SELECT name, count FROM crash_components WHERE category = ? AND filter = ?",
        bind: [category, filter],
        ...sqlOptions,
    });
    const entries = rows.map((r) => ({ name: r.name as string, count: r.count as number }));
    entries.sort((a, b) => b.count - a.count);
    return entries;
}

function stageFilters(db: Database, category: string): string[] {
    const rows = db.exec({
        sql: "SELECT DISTINCT filter FROM crash_components WHERE category = ?",
        bind: [category],
        ...sqlOptions,
    });
    const filters = rows.map((r) => r.filter as string);
    // Put "all" first, then percentiles in ascending order
    filters.sort((a, b) => {
        if (a === "all") return -1;
        if (b === "all") return 1;
        const na = parseInt(a, 10) || 0;
        const nb = parseInt(b, 10) || 0;
        return na - nb;
    });
    return filters;
}

// Human label for a crash_components filter value
function filterLabel(filter: string): string {
    if (filter === "all") {
        return "all sizes";
    }
    const m = filter.match(/^(\d+)th_percentile_on_(.+)$/);
    if (m) {
        const variable = m[2] === "text_size" ? ".text" : m[2];
        return `smallest ${m[1]}% (${variable})`;
    }
    return filter;
}

// ---- Bar lists -----------------------------------------------------------

function renderBars(entries: StageEntry[], limit: number, twoCol: boolean): HTMLElement {
    const shown = entries.slice(0, limit);
    const total = entries.reduce((a, e) => a + e.count, 0) || 1;
    const max = Math.max(1, ...shown.map((e) => e.count));

    const container = h("div", { class: twoCol ? "bars two-col" : "bars" });
    for (const e of shown) {
        const bar = h(
            "div",
            { class: "bar" },
            h(
                "div",
                { class: "bar-top" },
                h("span", { class: "bar-name", title: e.name }, e.name),
                h(
                    "span",
                    { class: "bar-val" },
                    `${commas(e.count)} - ${percent(e.count, total)}`
                )
            ),
            h(
                "div",
                { class: "bar-track" },
                h("div", {
                    class: "bar-fill",
                    style: { width: `${(e.count / max) * 100}%` },
                })
            )
        );
        container.append(bar);
    }
    return container;
}

// A block with a title, an optional percentile dropdown and a bars list that
// re-renders when the dropdown changes. Used both on the overview (one column
// per category) and on the detail pages. `onFilter` lets callers hook extra
// updates (e.g. swapping the flamegraph on detail pages).
interface StageBlock {
    pctlRow?: HTMLElement; // the "Binary size" label + dropdown, when >1 filter
    barsHost: HTMLElement;
    initialFilter: string;
    count: number; // number of stages at the initial filter
}

function stageBlock(
    db: Database,
    category: string,
    opts: { limit: number; twoCol: boolean; onFilter?: (filter: string) => void }
): StageBlock {
    const filters = stageFilters(db, category);
    const initialFilter = filters.includes("all") ? "all" : filters[0];
    const barsHost = h("div", {});

    const renderFilter = (filter: string) => {
        barsHost.innerHTML = "";
        barsHost.append(renderBars(stageEntries(db, category, filter), opts.limit, opts.twoCol));
    };
    const initialEntries = stageEntries(db, category, initialFilter);
    barsHost.append(renderBars(initialEntries, opts.limit, opts.twoCol));

    let pctlRow: HTMLElement | undefined;
    if (filters.length > 1) {
        const select = h("select", { class: "pctl" }) as HTMLSelectElement;
        for (const f of filters) {
            const option = h("option", { value: f }, filterLabel(f)) as HTMLOptionElement;
            if (f === initialFilter) option.selected = true;
            select.append(option);
        }
        select.addEventListener("change", () => {
            renderFilter(select.value);
            opts.onFilter?.(select.value);
        });
        pctlRow = h(
            "div",
            { class: "pctl-row" },
            h("span", { class: "lbl" }, "Binary size"),
            select
        );
    }

    return { pctlRow, barsHost, initialFilter, count: initialEntries.length };
}

