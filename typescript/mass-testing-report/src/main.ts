function renderBinaryDetail(root: HTMLElement, db: Database, meta: Metadata) {
    const hash = window.location.hash;
    if (!hash.startsWith("#")) {
        return;
    }
    const name = hash.slice(1);
    document.getElementsByTagName("title")[0].innerHTML += ` ${name}`;

    const rows = db.exec({ sql: "SELECT * FROM main WHERE name = ?", bind: [name], ...sqlOptions });
    const container = h("div", { class: "app" });
    const panel = h("div", { class: "panel" });
    const content = h("div", { class: "content" });
    panel.append(content);
    container.append(panel);
    root.append(container);

    content.append(
        h(
            "div",
            { class: "topbar", style: { padding: "0 0 18px", background: "transparent", border: "0" } },
            h(
                "div",
                { class: "brand" },
                h(
                    "a",
                    {
                        href: "index.html",
                        class: "brand-sub back-link",
                    },
                    icon("back"),
                    "Mass Testing"
                )
            )
        )
    );

    if (rows.length === 0) {
        content.append(h("h2", { class: "detail-title" }, `No data for ${name}`));
        return;
    }
    const data: Record<string, any> = rows[0];

    content.append(h("h2", { class: "detail-title" }, name));

    const ctx: TableContext = { setSearch: () => {} };
    const table = h("table", { class: "detail-table" });
    const tbody = h("tbody");
    table.append(tbody);
    for (const column of getColumns(meta, ctx, true)) {
        if (column.title === "Actions") continue;
        const tr = h("tr");
        const key = column.title || column.name || "";
        const tdKey = h("th", {}, String(key));
        const tdValue = h("td", {});
        const colData = data[(column as any).data as string];
        if (column.render !== undefined && (column.useRenderForDetail ?? true)) {
            const cell = column.render(colData, "display", data);
            if (cell instanceof HTMLElement) {
                tdValue.append(cell);
            } else {
                tdValue.innerHTML = cell;
            }
        } else {
            tdValue.textContent = colData === undefined || colData === null ? "" : String(colData);
        }
        tr.append(tdKey, tdValue);
        tbody.append(tr);
    }
    // Actions row
    const trActions = h("tr");
    trActions.append(h("th", {}, "Actions"), h("td", {}, actionsButton(data, meta, true)));
    tbody.append(trActions);

    content.append(table);
}

// ---- Entrypoint ----------------------------------------------------------

async function main() {
    const db = await loadDBFromURL("main.db");
    window.db = db;

    const metaReq = await fetch("meta.yml");
    const meta: Metadata = yaml.parse(await metaReq.text());

    // Binary detail is a standalone page
    const detailRoot = document.getElementById("binary-detail");
    if (detailRoot !== null) {
        renderBinaryDetail(detailRoot, db, meta);
        return;
    }

    const pageRoot = document.getElementById("page");
    if (pageRoot === null) {
        return;
    }
    const pageKey = pageRoot.getAttribute("data-page") || "overview";
    const cfg = PAGES[pageKey] || PAGES["overview"];
    const content = buildChrome(pageRoot, meta, cfg);

    if (cfg.page === "overview") {
        renderOverview(content, db, meta);
    } else if (cfg.category) {
        renderDetail(content, db, meta, cfg);
    } else {
        renderList(content, db, meta, cfg);
    }
}

