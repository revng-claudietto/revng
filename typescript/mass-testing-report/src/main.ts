// Minimal hyperscript helper. `attrs` supports: class, text, html, style
// (object), on<Event> handlers, and any other key becomes an attribute.
function h(tag: string, attrs?: Record<string, any> | null, ...children: any[]): HTMLElement {
    const e = document.createElement(tag);
    if (attrs) {
        for (const [k, v] of Object.entries(attrs)) {
            if (v === undefined || v === null || v === false) {
                continue;
            } else if (k === "class") {
                e.className = v;
            } else if (k === "text") {
                e.textContent = String(v);
            } else if (k === "html") {
                e.innerHTML = v;
            } else if (k === "style" && typeof v === "object") {
                Object.assign(e.style, v);
            } else if (k.startsWith("on") && typeof v === "function") {
                e.addEventListener(k.slice(2).toLowerCase(), v);
            } else {
                e.setAttribute(k, String(v));
            }
        }
    }
    for (const c of children.flat()) {
        if (c === null || c === undefined || c === false) continue;
        e.append(c instanceof Node ? c : document.createTextNode(String(c)));
    }
    return e;
}

