function renderDetail(content: HTMLElement, db: Database, meta: Metadata, cfg: PageConfig) {
    const s = statusStats(db);
    const count = statusCount(s, cfg.status!);
    const nSig = distinctSignatures(db, cfg.status!);

    // Summary note
    let note = `across ${commas(nSig)} stacktraces`;
    const conf = meta.configurations?.[0];
    if (cfg.status === "CRASHED") {
        note = `across ${commas(nSig)} crash signatures`;
    } else if (cfg.status === "TIMED_OUT" && conf?.timeout) {
        note = `${conf.timeout} s wall-clock limit - ${commas(nSig)} stacktraces`;
    } else if (cfg.status === "OOM" && conf?.memory_limit) {
        note = `${filesize(conf.memory_limit, { base: 2 })} memory limit - ${commas(nSig)} stacktraces`;
    }

    // Summary card + stage breakdown
    const summary = summaryCard(cfg, count, s.total, note);

    // The flamegraph card is created first so the stage block can update it
    const fgHost = h("div", {});
    const updateFlamegraph = (filter: string) => {
        fgHost.innerHTML = "";
        fgHost.append(flamegraphImages(cfg.fgPrefix!, filter, cfg.fgEnd!));
    };

    const block = stageBlock(db, cfg.category!, {
        limit: 8,
        twoCol: true,
        onFilter: updateFlamegraph,
    });
    updateFlamegraph(block.initialFilter);

    const stageHead = h(
        "div",
        { class: "comp-head", style: { marginBottom: "14px" } },
        h("span", { class: "card-label" }, "By pipeline stage")
    );
    if (block.pctlRow) {
        stageHead.append(block.pctlRow);
    }
    const stageCard = h("div", { class: `card ${cfg.accent}` }, stageHead, block.barsHost);

    content.append(h("div", { class: "summary-grid" }, summary, stageCard));

    // Flamegraphs card
    content.append(
        h(
            "div",
            { class: "fg-card" },
            h("div", { class: "fg-title" }, "Flamegraphs"),
            h(
                "div",
                { class: "fg-hint" },
                `Aggregated stack traces - ${cfg.fgEnd} location at the top`
            ),
            fgHost
        )
    );

    // Data table
    buildTable(content, db, meta, cfg);
}

